/**
 * `deno task contract:update --tag v<ver> [--from <appHome>] [--no-sync] [--check]` (OSS-PLAN §2.3, T46): pins one
 * Herdr version's contract for the bridge's start-time compat check.
 *
 * 1. `--from <appHome>`: captures `fixtures/contract/<ver>/` from an installed Herdr of exactly that version (read
 *    only): `herdr.d.ts`, `installed.json`, the newest shipped mod's `gpui-kit.d.ts` (not in the upstream repo: Herdr
 *    generates it), and `herdr-app commands` → `herdr-app-commands.json`.
 * 2. Unless `--no-sync`/`--check`: the fixture sync (`tools/fixtures/sync.ts --tag`), which refreshes
 *    `fixtures/generic-home` at that tag, including the `gpui-kit.d.ts` copies the style-name tests read.
 * 3. Re-hashes `fixtures/contract/<ver>/` into `packages/bridge/src/compat/pins.json` (other versions are kept);
 *    `--check` only compares.
 * 4. Checks what the pins cannot hold: every listed command has a class in `packages/bridge/src/policy/commands.json`;
 *    Herdr's own `sh -c` listing literal (E14, `mods/files/main.js` at that tag) is pinned for the version in
 *    `HERDR_SH_LITERALS` (`policy/exec.table.ts`) and in the `herdr-shipped` profile; the bundled `herdr/commands.json`
 *    matches the newest pinned capture. E15's literals are cockpit's (`show.js`), not Herdr's: no Herdr tag changes
 *    them. Each problem is printed with the entry to add; the exit code is 1 when there is any.
 */

import { join } from "@std/path";
import {
  CONTRACT_PINS,
  type ContractPins,
  testedVersions,
  type VersionPins,
} from "../../packages/bridge/src/compat/pins.ts";
import { observeCompat, parseCommandsCapture } from "../../packages/bridge/src/compat/check.ts";
import { HERDR_SH_LITERALS, herdrVersionOf } from "../../packages/bridge/src/policy/exec.table.ts";
import { classifyCommand } from "../../packages/bridge/src/session/commands.ts";
import bundled from "../../packages/bridge/src/herdr/commands.json" with { type: "json" };

const ROOT = new URL("../../", import.meta.url);
const PINS_FILE = new URL("packages/bridge/src/compat/pins.json", ROOT);
const GENERIC_HOME = new URL("fixtures/generic-home/", ROOT);
const SHIPPED_PROFILE = new URL("packages/bridge/profiles/herdr-shipped.json", ROOT);
const CONTRACT_FILES = ["herdr.d.ts", "gpui-kit.d.ts", "installed.json", "herdr-app-commands.json"] as const;

const PINS_COMMENT = [
  "Generated by `deno task contract:update --tag v<ver>` from fixtures/contract/<ver>/ (OSS-PLAN §2.3); do not edit.",
  "Per tested Herdr version: sha256 of herdr.d.ts and of the gpui-kit.d.ts Herdr writes into mod folders, Herdr's own installed.json hashes of the shipped mods and layouts, and the names herdr-app commands lists.",
];

async function sha256(bytes: Uint8Array<ArrayBuffer>): Promise<string> {
  const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", bytes));
  return Array.from(digest, (b) => b.toString(16).padStart(2, "0")).join("");
}

/** A copy of `value` with object keys sorted at every level (stable, reviewable JSON). */
function sorted(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sorted);
  if (typeof value !== "object" || value === null) return value;
  return Object.fromEntries(Object.keys(value).sort().map((k) => [k, sorted((value as Record<string, unknown>)[k])]));
}

/** The pins of one `fixtures/contract/<ver>/` directory. */
export async function versionPinsOf(dir: URL): Promise<VersionPins> {
  const read = (name: string) => Deno.readFile(new URL(name, dir));
  const installed = JSON.parse(new TextDecoder().decode(await read("installed.json")));
  const capture = parseCommandsCapture(new TextDecoder().decode(await read("herdr-app-commands.json")));
  if (!capture.ok) throw new Error(`${new URL("herdr-app-commands.json", dir).pathname}: ${capture.reason}`);
  return {
    herdrDts: await sha256(await read("herdr.d.ts")),
    gpuiKitDts: await sha256(await read("gpui-kit.d.ts")),
    installed: sorted(installed) as VersionPins["installed"],
    commands: capture.names,
  };
}

/** The pins file text with `pins` for `version` merged in (versions ordered oldest first). */
export function pinsFileText(current: ContractPins, version: string, pins: VersionPins): string {
  const all: ContractPins = { versions: { ...current.versions, [version]: pins } };
  const versions = Object.fromEntries(testedVersions(all).map((v) => [v, all.versions[v]]));
  return `${JSON.stringify({ $comment: PINS_COMMENT, versions }, null, 2)}\n`;
}

/**
 * Herdr's own `sh -c` listing literal (E14) in `mods/files/main.js`: the `const script = '…'` single-quoted string,
 * unescaped as JavaScript would (the mod is read as text, never run).
 */
export function listingLiteral(source: string): string | null {
  const m = /\bconst script = '((?:[^'\\\n]|\\.)*)';/.exec(source);
  if (m === null) return null;
  const escapes: Record<string, string> = { n: "\n", t: "\t", r: "\r", b: "\b", f: "\f", v: "\v", "0": "\0" };
  return m[1].replace(
    /\\(x[0-9a-fA-F]{2}|u[0-9a-fA-F]{4}|.)/g,
    (_, e: string) => e.length > 1 ? String.fromCharCode(parseInt(e.slice(1), 16)) : escapes[e] ?? e,
  );
}

/** Copies the contract files of an installed Herdr (`--from`) into `dir`; the version it reports must be `version`. */
async function capture(appHome: string, version: string, dir: URL): Promise<void> {
  const env = { HOME: Deno.env.get("HOME") ?? "", PATH: Deno.env.get("PATH") ?? "", HERDR_APP_HOME: appHome };
  const run = async (args: string[]) => {
    const out = await new Deno.Command("herdr-app", { args, env, clearEnv: true, stdin: "null" }).output();
    if (!out.success) throw new Error(`herdr-app ${args.join(" ")} exited ${out.code}`);
    return new TextDecoder().decode(out.stdout);
  };
  const reported = herdrVersionOf(await run(["--version"]));
  if (reported !== version) throw new Error(`${appHome} runs Herdr ${reported ?? "(unknown)"}, not ${version}`);
  const commands = await run(["commands"]);
  const parsed = parseCommandsCapture(commands);
  if (!parsed.ok) throw new Error(parsed.reason);
  const observed = await observeCompat(appHome, parsed);
  if (observed.gpuiKit === null) throw new Error(`${appHome}: no shipped mod folder has a gpui-kit.d.ts`);
  await Deno.mkdir(dir, { recursive: true });
  await Deno.copyFile(join(appHome, "herdr.d.ts"), new URL("herdr.d.ts", dir));
  await Deno.copyFile(join(appHome, "installed.json"), new URL("installed.json", dir));
  await Deno.copyFile(join(appHome, "mods", observed.gpuiKit.mod, "gpui-kit.d.ts"), new URL("gpui-kit.d.ts", dir));
  await Deno.writeTextFile(
    new URL("herdr-app-commands.json", dir),
    `${JSON.stringify(JSON.parse(commands), null, 2)}\n`,
  );
  console.log(`captured ${CONTRACT_FILES.join(", ")} from ${appHome} (gpui-kit.d.ts of mods/${observed.gpuiKit.mod})`);
}

async function syncFixtures(tag: string): Promise<void> {
  const status = await new Deno.Command("deno", {
    args: [
      "run",
      "--allow-read=fixtures",
      "--allow-write=fixtures/generic-home",
      "--allow-net=api.github.com,raw.githubusercontent.com",
      "tools/fixtures/sync.ts",
      "--tag",
      tag,
    ],
    cwd: ROOT,
    stdout: "inherit",
    stderr: "inherit",
  }).spawn().status;
  if (!status.success) throw new Error(`tools/fixtures/sync.ts --tag ${tag} failed`);
}

/** What the pins cannot hold: classes, the E14 literal, the bundled commands list. */
async function crossChecks(tag: string, version: string, pins: VersionPins, newest: boolean): Promise<string[]> {
  const problems: string[] = [];
  const unclassified = pins.commands.filter((n) => classifyCommand(n).class === "unknown");
  if (unclassified.length > 0) {
    problems.push(
      `commands without a class (refused on devices until packages/bridge/src/policy/commands.json lists them): ${
        unclassified.join(", ")
      }`,
    );
  }
  const manifest = JSON.parse(await Deno.readTextFile(new URL("MANIFEST.json", GENERIC_HOME)));
  if (manifest.tag !== tag) {
    console.log(`skipped the E14 literal check: fixtures/generic-home is at ${manifest.tag}, not ${tag}`);
  } else {
    if (await sha256(await Deno.readFile(new URL("herdr.d.ts", GENERIC_HOME))) !== pins.herdrDts) {
      problems.push(`fixtures/generic-home/herdr.d.ts differs from fixtures/contract/${version}/herdr.d.ts`);
    }
    const literal = listingLiteral(await Deno.readTextFile(new URL("mods/files/main.js", GENERIC_HOME)));
    if (literal === null) {
      problems.push("fixtures/generic-home/mods/files/main.js: no `const script = '…'` listing literal (E14) found");
    } else {
      const hash = await sha256(new TextEncoder().encode(literal));
      if (HERDR_SH_LITERALS[version]?.[hash] !== "listing") {
        problems.push(
          `packages/bridge/src/policy/exec.table.ts HERDR_SH_LITERALS lacks "${version}": { "${hash}": "listing" }`,
        );
      }
      const profiles: { id: string; shLiterals?: Record<string, string> }[] = JSON.parse(
        await Deno.readTextFile(SHIPPED_PROFILE),
      );
      if (profiles.find((p) => p.id === "herdr-shipped")?.shLiterals?.[hash] !== "listing") {
        problems.push(`packages/bridge/profiles/herdr-shipped.json shLiterals lacks "${hash}": "listing"`);
      }
    }
  }
  const bundledNames = bundled.commands.map((c) => c.name).sort();
  if (newest && JSON.stringify(bundledNames) !== JSON.stringify(pins.commands)) {
    problems.push(
      `packages/bridge/src/herdr/commands.json (served before the mirror reports) differs from Herdr ${version}'s ` +
        `herdr-app commands: regenerate it from fixtures/contract/${version}/herdr-app-commands.json`,
    );
  }
  return problems;
}

async function main(args: string[]): Promise<number> {
  const flag = (name: string) => {
    const at = args.indexOf(name);
    return at < 0 ? undefined : args[at + 1];
  };
  const tag = flag("--tag");
  const from = flag("--from");
  const check = args.includes("--check");
  if (!tag || !/^v\d+\.\d+\.\d+$/.test(tag) || (args.includes("--from") && !from)) {
    console.error(
      "usage: deno task contract:update --tag v<major.minor.patch> [--from <appHome>] [--no-sync] [--check]",
    );
    return 2;
  }
  const version = tag.slice(1);
  const dir = new URL(`fixtures/contract/${version}/`, ROOT);
  if (from !== undefined) {
    if (check) throw new Error("--check compares only; it does not capture (--from)");
    await capture(from, version, dir);
  }
  if (!check && !args.includes("--no-sync")) await syncFixtures(tag);
  for (const name of CONTRACT_FILES) {
    try {
      await Deno.stat(new URL(name, dir));
    } catch {
      throw new Error(
        `fixtures/contract/${version}/${name} is missing: capture it with --from <appHome of Herdr ${version}>`,
      );
    }
  }
  const pins = await versionPinsOf(dir);
  const problems: string[] = [];
  const text = pinsFileText(CONTRACT_PINS, version, pins);
  if (check) {
    const committed = await Deno.readTextFile(PINS_FILE);
    if (committed !== text) {
      problems.push(`packages/bridge/src/compat/pins.json is stale for ${version}: run without --check`);
    }
  } else {
    await Deno.writeTextFile(PINS_FILE, text);
    console.log(`pinned Herdr ${version} in packages/bridge/src/compat/pins.json`);
  }
  const newest = testedVersions({ versions: { ...CONTRACT_PINS.versions, [version]: pins } }).at(-1) === version;
  problems.push(...await crossChecks(tag, version, pins, newest));
  for (const p of problems) console.error(`problem: ${p}`);
  if (problems.length === 0) console.log(`Herdr ${version}: contract pins, classes and the E14 literal agree`);
  return problems.length === 0 ? 0 : 1;
}

if (import.meta.main) {
  try {
    Deno.exit(await main(Deno.args));
  } catch (e) {
    console.error(`contract:update: ${e instanceof Error ? e.message : String(e)}`);
    Deno.exit(1);
  }
}
